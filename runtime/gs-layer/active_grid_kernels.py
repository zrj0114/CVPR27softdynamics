"""Active-node versions of the selected grid kernels.

Generated by build_active_kernels.py. Tests require the bodies following the
index mapping to be AST-identical to the authoritative dense kernels. Every
quadratic B-spline support node is enumerated by DeterministicTransfer; empty
nodes outside that union cannot affect G2P. Zero each newly active grid node
before use. The original contact/ground bodies clear their accumulators after
use, and branch restore additionally clears all scratch grids.
"""
import warp as wp
from material_contact_kernels import MPMStateStruct, MPMModelStruct, MaterialContact, contact_delta

wp.set_module_options({'enable_backward': False, 'max_unroll': 1})
ACTIVE_THREADS = 32768


@wp.kernel
def active_zero_grid(state: MPMStateStruct, model: MPMModelStruct, nodes: wp.array(dtype=int), count: wp.array(dtype=int), grid: int):
    for slot in range(wp.tid(), count[0], ACTIVE_THREADS):
        active_node_id = nodes[slot]
        grid_x = active_node_id / (grid * grid)
        grid_y = active_node_id / grid % grid
        grid_z = active_node_id % grid
        state.grid_m[grid_x, grid_y, grid_z] = 0.0
        state.grid_v_in[grid_x, grid_y, grid_z] = wp.vec3(0.0, 0.0, 0.0)
        state.grid_v_out[grid_x, grid_y, grid_z] = wp.vec3(0.0, 0.0, 0.0)

@wp.kernel
def active_grid_normalization_and_gravity(state: MPMStateStruct, model: MPMModelStruct, dt: float, nodes: wp.array(dtype=int), count: wp.array(dtype=int), grid: int):
    for slot in range(wp.tid(), count[0], ACTIVE_THREADS):
        active_node_id = nodes[slot]
        grid_x = active_node_id / (grid * grid)
        grid_y = active_node_id / grid % grid
        grid_z = active_node_id % grid
        if state.grid_m[grid_x, grid_y, grid_z] > 1e-15:
            v_out = state.grid_v_in[grid_x, grid_y, grid_z] * (1.0 / state.grid_m[grid_x, grid_y, grid_z])
            v_out = v_out + dt * model.gravitational_accelaration
            state.grid_v_out[grid_x, grid_y, grid_z] = v_out

@wp.kernel
def active_add_damping_via_grid(state: MPMStateStruct, scale: float, nodes: wp.array(dtype=int), count: wp.array(dtype=int), grid: int):
    for slot in range(wp.tid(), count[0], ACTIVE_THREADS):
        active_node_id = nodes[slot]
        grid_x = active_node_id / (grid * grid)
        grid_y = active_node_id / grid % grid
        grid_z = active_node_id % grid
        wp.atomic_sub(state.grid_v_out, grid_x, grid_y, grid_z, (1.0 - scale) * state.grid_v_out[grid_x, grid_y, grid_z])

@wp.kernel
def active_accumulate_pad_contact(t: float, dt: float, state: MPMStateStruct, model: MPMModelStruct, c: MaterialContact, nodes: wp.array(dtype=int), count: wp.array(dtype=int), grid: int):
    for slot in range(wp.tid(), count[0], ACTIVE_THREADS):
        active_node_id = nodes[slot]
        i = active_node_id / (grid * grid)
        j = active_node_id / grid % grid
        k = active_node_id % grid
        if state.grid_m[i, j, k] > 1e-12:
            node = wp.vec3(float(i), float(j), float(k)) / c.inv_dx
            free = state.grid_v_out[i, j, k]
            delta = wp.vec3(0.0)
            weight = float(0.0)
            for side in range(2):
                if c.enabled[side] != 0:
                    tau = wp.max(0.0, t - c.frame_time)
                    tr = c.transforms[side]
                    q = wp.transform_get_rotation(tr)
                    omega = c.angular[side]
                    speed = wp.length(omega)
                    if speed > 1e-10:
                        q = wp.quat_from_axis_angle(omega / speed, speed * tau) * q
                    origin = wp.transform_get_translation(tr) + tau * c.linear[side]
                    local = wp.quat_rotate_inv(q, node - origin)
                    sign = float(1.0)
                    if side == 1:
                        sign = -1.0
                    distance = sign * local[0]
                    if wp.abs(local[1]) <= c.footprint_y and wp.abs(local[2]) <= c.footprint_z and (distance <= 0.0) and (distance >= -c.radius):
                        normal = wp.quat_rotate(q, wp.vec3(sign, 0.0, 0.0))
                        controller = c.linear[side] + wp.cross(omega, node - origin)
                        relative = free - controller
                        if wp.dot(relative, normal) < 0.0:
                            delta = delta + contact_delta(relative, normal, c.contact_friction, c.sliding_friction)
                            weight = weight + 1.0
            c.momentum[i, j, k] = c.momentum[i, j, k] + delta
            c.weight[i, j, k] = c.weight[i, j, k] + weight

@wp.kernel
def active_material_grid_boundary(t: float, dt: float, state: MPMStateStruct, model: MPMModelStruct, c: MaterialContact, nodes: wp.array(dtype=int), count: wp.array(dtype=int), grid: int):
    for slot in range(wp.tid(), count[0], ACTIVE_THREADS):
        active_node_id = nodes[slot]
        i = active_node_id / (grid * grid)
        j = active_node_id / grid % grid
        k = active_node_id % grid
        if state.grid_m[i, j, k] > 1e-12:
            v = state.grid_v_out[i, j, k] + c.momentum[i, j, k] / wp.max(1.0, c.weight[i, j, k])
            if float(j) * model.dx < c.ground and v[1] < 0.0:
                speed = wp.sqrt(v[0] * v[0] + v[2] * v[2])
                factor = wp.max(0.0, 1.0 + c.friction * v[1] / wp.max(speed, 1e-12))
                v = wp.vec3(v[0] * factor, 0.0, v[2] * factor)
            state.grid_v_out[i, j, k] = v
        c.momentum[i, j, k] = wp.vec3(0.0)
        c.weight[i, j, k] = 0.0
